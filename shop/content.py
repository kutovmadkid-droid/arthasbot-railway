def money(cents):
    return f"{cents // 100}.{cents % 100:02d}"


def parse_price(text):
    try:
        value = Decimal(text.strip().replace(",", "."))
        if (
            not value.is_finite()
            or value != value.quantize(Decimal("0.01"))
            or not Decimal("0.01") <= value <= Decimal("1000000")
        ):
            raise ValueError
        return int(value * 100)
    except (InvalidOperation, ValueError):
        raise ValueError("Введите цену от 0.01 до 1000000.00, не более двух знаков после точки") from None


def caption_units(html):
    plain = unescape(re.sub(r"<[^>]+>", "", html))
    return len(plain.encode("utf-16-le")) // 2


def esc(value):
    return escape(str(value), quote=False)


def short(value, limit=32):
    value = str(value)
    return value if len(value) <= limit else value[: limit - 1] + "…"


def validate_support(value):
    value = value.strip().lstrip("@")
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]{4,31}", value):
        raise ValueError("Username: 5–32 латинских символа, цифры и _, без ссылки")
    return value
